// Map readonly literal types to mutable widened types so locales like bg can
// supply different strings while keeping the same structural shape.
type Widen<T> =
  T extends string ? string :
  T extends (...args: infer A) => infer R ? (...args: A) => R :
  T extends object ? { [K in keyof T]: Widen<T[K]> } :
  T
export type Translations = Widen<typeof en>

// Helper to look up a translated name, falling back to the original.
export function tx(dict: Record<string, string>, key: string): string {
  return dict[key] ?? key
}
